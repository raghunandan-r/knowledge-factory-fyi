    form_of_payment_or_transfer_of_value as form_of_payment,
    nature_of_payment_or_transfer_of_value as nature_of_payment,
    state_of_travel,
    country_of_travel,
    physician_ownership_indicator,
    third_party_payment_recipient_indicator,
    name_of_third_party_entity_receiving_payment_or_transfer_of_value as third_party_entity_name,
    charity_indicator,
    dispute_status_for_publication as dispute_status,
    delay_in_publication_indicator,
    related_product_indicator,
    covered_or_noncovered_indicator_1 as product_1_covered_indicator,
    indicate_drug_or_biological_or_device_or_medical_supply_1 as product_1_type,
    product_category_or_therapeutic_area_1 as product_1_category,
    name_of_drug_or_biological_or_device_or_medical_supply_1 as product_1_name,
    associated_drug_or_biological_ndc_1 as product_1_ndc
