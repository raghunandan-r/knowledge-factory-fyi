-- One row per prescriber NPI x data year (Part D Prescribers by Provider).
select
    prscrbr_npi || '-' || data_year as prescriber_year_id,
    data_year,
    make_date(data_year, 1, 1) as data_year_start,
    prscrbr_npi as npi,
    prscrbr_last_org_name as prescriber_last_org_name,
    prscrbr_first_name as prescriber_first_name,
    prscrbr_crdntls as prescriber_credentials,
    prscrbr_ent_cd as prescriber_entity_code,
    prscrbr_city as prescriber_city,
    prscrbr_state_abrvtn as prescriber_state,
    prscrbr_zip5 as prescriber_zip5,
    prscrbr_ruca_desc as prescriber_ruca_desc,
    prscrbr_type as prescriber_type,
    prscrbr_type_src as prescriber_type_source,
    tot_clms as total_claims,
    tot_30day_fills as total_30day_fills,
    tot_day_suply as total_day_supply,
    tot_drug_cst as total_drug_cost,
    tot_benes as total_beneficiaries,
    brnd_tot_clms as brand_claims,
    brnd_tot_drug_cst as brand_drug_cost,
    gnrc_tot_clms as generic_claims,
    gnrc_tot_drug_cst as generic_drug_cost,
    opioid_tot_clms as opioid_claims,
    opioid_tot_drug_cst as opioid_drug_cost,
    opioid_tot_benes as opioid_beneficiaries,
    opioid_prscrbr_rate as opioid_prescribing_rate,
    opioid_la_tot_clms as long_acting_opioid_claims,
    antbtc_tot_clms as antibiotic_claims,
    bene_avg_age as beneficiary_average_age,
    bene_avg_risk_scre as beneficiary_average_risk_score
from {{ ref('partd_prescribers') }}
